// Public-surface golden generator for otpless_flutter_web.
//
// Two surfaces matter for this package and neither is checked by the compiler:
//
//   1. THE DART SURFACE — everything a merchant can name after
//      `import 'package:otpless_flutter_web/otpless_flutter_web.dart'`.
//      Renaming `initiatePhoneAuth`, or its `request` parameter, is a breaking
//      change for a published pub.dev package. `dart analyze` says nothing.
//
//   2. THE JS-INTEROP SURFACE — the `window` function names this package calls
//      through `dart:js`: `initiateAuth`, `verifyAuth`, `startHeadless`,
//      `openLoginPage`, and the `getResponse` slot it installs. Those names are
//      implemented in a different repo (vegapunk's `src/auth-files/flutter.ts`,
//      shipped as https://otpless.com/v2/flutter.js). They are matched by
//      STRING at runtime. Rename one on either side and this package degrades
//      to "nothing happens, silently" — see the characterisation tests. This is
//      the same class of hazard as a reflection contract, so it gets the same
//      treatment: a committed golden.
//
// Usage:
//   dart run tool/api_dump.dart            # verify against api/*.txt (exit 1 on drift)
//   dart run tool/api_dump.dart --update   # accept the current surface
//
// Deliberately depends on `dart:io` only. Adding the `analyzer` package would
// force this package's `environment: sdk` lower bound up, which changes what
// merchants can resolve — not something a tooling change may do.

import 'dart:io';

const _dartGolden = 'api/public-surface.txt';
const _jsGolden = 'api/js-interop-surface.txt';

void main(List<String> args) {
  final update = args.contains('--update');

  final files = Directory('lib')
      .listSync(recursive: true)
      .whereType<File>()
      .where((f) => f.path.endsWith('.dart'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  if (files.isEmpty) {
    stderr.writeln('error: no .dart files found under lib/');
    exit(1);
  }

  final dartSurface = StringBuffer()
    ..writeln('# Public Dart surface of otpless_flutter_web.')
    ..writeln('# GENERATED by tool/api_dump.dart — do not hand-edit.')
    ..writeln('# Regenerate with: make surface-update')
    ..writeln('#')
    ..writeln('# Every line here is part of the pub.dev contract, including')
    ..writeln('# parameter names. Renaming one is a breaking change.');

  final jsNames = <String>{};

  for (final file in files) {
    final source = file.readAsStringSync();
    final relative = file.path.replaceAll(r'\', '/');

    dartSurface
      ..writeln()
      ..writeln('## $relative');
    for (final decl in _publicDeclarations(source)) {
      dartSurface.writeln(decl);
    }

    jsNames.addAll(_jsInteropNames(source));
  }

  final jsSurface = StringBuffer()
    ..writeln('# JS-interop contract of otpless_flutter_web.')
    ..writeln('# GENERATED by tool/api_dump.dart — do not hand-edit.')
    ..writeln('#')
    ..writeln('# `window` function names this package resolves BY STRING at')
    ..writeln('# runtime. They are implemented in the vegapunk repo')
    ..writeln(
        '# (src/auth-files/flutter.ts -> https://otpless.com/v2/flutter.js).')
    ..writeln(
        '# Nothing in either repo fails to compile if one is renamed; the')
    ..writeln(
        '# package just stops working, silently. Treat a change here as a')
    ..writeln('# cross-repo contract change.');
  final sortedJs = jsNames.toList()..sort();
  for (final name in sortedJs) {
    jsSurface.writeln(name);
  }

  final results = [
    _check(_dartGolden, dartSurface.toString(), update),
    _check(_jsGolden, jsSurface.toString(), update),
  ];

  if (results.any((ok) => !ok)) exit(1);
}

bool _check(String path, String actual, bool update) {
  final file = File(path);
  if (update) {
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(actual);
    stdout.writeln('updated $path');
    return true;
  }

  if (!file.existsSync()) {
    stderr.writeln('error: $path is missing. Run `make surface-update`.');
    return false;
  }

  final expected = file.readAsStringSync();
  if (expected == actual) {
    stdout.writeln('$path matches');
    return true;
  }

  stderr.writeln('');
  stderr.writeln('PUBLIC SURFACE CHANGED — $path is out of date.');
  stderr.writeln('');
  stderr.writeln('  - = committed golden   + = current source');
  stderr.writeln('');
  final a = expected.split('\n');
  final b = actual.split('\n');
  for (var i = 0; i < (a.length > b.length ? a.length : b.length); i++) {
    final left = i < a.length ? a[i] : null;
    final right = i < b.length ? b[i] : null;
    if (left != right) {
      if (left != null) stderr.writeln('  - $left');
      if (right != null) stderr.writeln('  + $right');
    }
  }
  stderr.writeln('');
  stderr.writeln('If this change is intentional, run `make surface-update`,');
  stderr.writeln('note it in CHANGELOG.md, and — for the JS-interop golden —');
  stderr.writeln('confirm the matching change has shipped in the CDN bundle.');
  stderr.writeln('');
  return false;
}

/// Strips comments, keeping string literals intact.
String _stripComments(String src) {
  final out = StringBuffer();
  var i = 0;
  while (i < src.length) {
    final c = src[i];
    final next = i + 1 < src.length ? src[i + 1] : '';
    if (c == '/' && next == '/') {
      while (i < src.length && src[i] != '\n') {
        i++;
      }
    } else if (c == '/' && next == '*') {
      i += 2;
      while (i + 1 < src.length && !(src[i] == '*' && src[i + 1] == '/')) {
        i++;
      }
      i += 2;
    } else if (c == "'" || c == '"') {
      final quote = c;
      out.write(c);
      i++;
      while (i < src.length) {
        if (src[i] == r'\') {
          out.write(src[i]);
          if (i + 1 < src.length) out.write(src[i + 1]);
          i += 2;
          continue;
        }
        out.write(src[i]);
        if (src[i] == quote) {
          i++;
          break;
        }
        i++;
      }
    } else {
      out.write(c);
      i++;
    }
  }
  return out.toString();
}

/// Public declarations at top level (depth 0) and as type members (depth 1).
///
/// A deliberately small scanner: it collects the text preceding each `{`, `;`
/// or `=>` and reports it if it is a public declaration. Enforced `dart format`
/// keeps the input regular enough for this to be reliable; if it ever is not,
/// the golden drifts loudly rather than silently, which is the failure mode we
/// want.
List<String> _publicDeclarations(String rawSource) {
  final src = _stripComments(rawSource);
  final decls = <String>[];
  final buffer = StringBuffer();
  var depth = 0;

  void flush(int atDepth) {
    final text = buffer.toString().replaceAll(RegExp(r'\s+'), ' ').trim();
    buffer.clear();
    if (text.isEmpty) return;
    if (atDepth > 1) return;
    if (_isPrivateOrNoise(text)) return;
    decls.add('${'  ' * atDepth}$text');
  }

  var i = 0;
  while (i < src.length) {
    final c = src[i];
    if (c == '{') {
      flush(depth);
      depth++;
      i++;
    } else if (c == '}') {
      buffer.clear();
      if (depth > 0) depth--;
      i++;
    } else if (c == ';') {
      flush(depth);
      i++;
    } else if (c == '=' && i + 1 < src.length && src[i + 1] == '>') {
      // Expression body / arrow: record the signature, discard the body.
      flush(depth);
      while (i < src.length && src[i] != ';') {
        i++;
      }
    } else {
      buffer.write(c);
      i++;
    }
  }
  return decls;
}

final _identifier = RegExp(r'[A-Za-z_][A-Za-z0-9_]*');

bool _isPrivateOrNoise(String text) {
  if (text.startsWith('import ') ||
      text.startsWith('export ') ||
      text.startsWith('part ') ||
      text.startsWith('@')) {
    return true;
  }
  // Any private identifier appearing as a declared name.
  for (final m in _identifier.allMatches(text)) {
    if (m.group(0)!.startsWith('_')) return true;
  }
  return false;
}

/// `window` names resolved by string: the second argument of every
/// `executeFunction(...)` call site, plus every `js.context['name']` access.
Set<String> _jsInteropNames(String rawSource) {
  final src = _stripComments(rawSource);
  final names = <String>{};

  final execCall = RegExp(
    r'''executeFunction\s*\([^,()]*,\s*["']([^"']+)["']''',
    dotAll: true,
  );
  for (final m in execCall.allMatches(src)) {
    names.add('${m.group(1)}  (called on window)');
  }

  final contextAccess = RegExp(r'''js\.context\[\s*["']([^"']+)["']\s*\]''');
  for (final m in contextAccess.allMatches(src)) {
    names.add('${m.group(1)}  (installed on window by this package)');
  }

  return names;
}
